-- 2) Öffentliche Spielerprofile: nur die ausdrücklich öffentlichen Felder zurückgeben.
create or replace function public.get_public_profile_v68(p_user_id uuid)
returns jsonb
language sql
stable
security definer
set search_path=public
as $$
 select case when p.id is null then null else jsonb_build_object(
   'id',p.id,
   'display_name',p.display_name,
   'bio',coalesce(p.bio,''),
   'avatar_path',p.avatar_path,
   'wins',p.wins,
   'total_games',p.total_games,
   'total_fields_revealed',p.total_fields_revealed,
   'gold_found_ug',p.gold_found_ug
 ) end
 from (select 1) x
 left join public.profiles p on p.id=p_user_id
 where auth.uid() is not null;
$$;
revoke all on function public.get_public_profile_v68(uuid) from public;
grant execute on function public.get_public_profile_v68(uuid) to authenticated;

-- 3) Spielchat
create table if not exists public.game_messages(
 id bigint generated by default as identity primary key,
 game_id uuid not null references public.games(id) on delete cascade,
 user_id uuid not null references public.profiles(id) on delete cascade,
 display_name text not null,
 message text not null check(char_length(message) between 1 and 500),
 created_at timestamptz not null default now()
);
create index if not exists game_messages_game_created_idx on public.game_messages(game_id,created_at desc);
alter table public.game_messages enable row level security;

drop policy if exists "v68 game chat member read" on public.game_messages;
create policy "v68 game chat member read" on public.game_messages
for select to authenticated
using(exists(select 1 from public.game_players gp where gp.game_id=game_messages.game_id and gp.user_id=auth.uid()));

-- Direkte INSERTs bleiben verboten; Schreiben nur über RPC.
create or replace function public.send_game_message_v68(p_game_id uuid,p_message text)
returns bigint
language plpgsql
security definer
set search_path=public
as $$
declare
  mid bigint;
  clean text:=trim(coalesce(p_message,''));
  n text;
begin
 if auth.uid() is null then raise exception 'Nicht angemeldet'; end if;
 if not exists(select 1 from game_players where game_id=p_game_id and user_id=auth.uid()) then
   raise exception 'Nur Spielteilnehmer können schreiben';
 end if;
 if char_length(clean)<1 or char_length(clean)>500 then raise exception 'Nachricht muss 1 bis 500 Zeichen haben'; end if;
 select display_name into n from profiles where id=auth.uid();
 insert into game_messages(game_id,user_id,display_name,message)
 values(p_game_id,auth.uid(),coalesce(n,'Spieler'),clean)
 returning id into mid;
 return mid;
end;
$$;
revoke all on function public.send_game_message_v68(uuid,text) from public;
grant execute on function public.send_game_message_v68(uuid,text) to authenticated;

